/**
 * توحيد نصُّ الجملة لمفاتيح الترجمة: إزالة التشكيل وعلامات الترقيم والأقواس
 * والاقتباسات ودمج المسافات — نفس الدوال تُستخدم وقت البناء وفي المتصفح.
 */
export function normSentence(s: string): string {
  return s
    .toLowerCase()
    // حركات التشكيل العربية + علامات ترقيم القرآن
    .replace(/[\u064B-\u065F\u0670\u06D6-\u06ED]/g, '')
    // كل ما ليس حرفاً أو رقماً أو مسافة يتحول إلى مسافة
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
